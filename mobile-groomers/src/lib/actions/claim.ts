"use server";

import { createClient, getCurrentUser } from "@/lib/supabase/server";
import { isSupabaseConfigured } from "@/lib/supabase/config";

/**
 * Files an ownership claim for a listing. The claim is recorded as pending;
 * listings are never auto-assigned, because handing a business page to
 * whoever asks first would let a competitor take over a rival's listing.
 */
export async function submitClaim(formData: FormData) {
  const businessName = String(formData.get("biz-name") ?? "").trim();
  const city = String(formData.get("city") ?? "").trim();
  const phone = String(formData.get("phone") ?? "").trim();
  const email = String(formData.get("email") ?? "").trim();
  const listingSlug = String(formData.get("listing") ?? "").trim();
  const listingCitySlug = String(formData.get("city_slug") ?? "").trim();

  if (!businessName || !email) {
    return { error: "Business name and email are required." };
  }

  if (!isSupabaseConfigured) {
    return { ok: true, stored: false };
  }

  const supabase = await createClient();
  if (!supabase) return { ok: true, stored: false };

  const user = await getCurrentUser();
  if (!user) {
    // Not signed in yet: send the magic link, and the claim is filed once
    // they land back on the site authenticated.
    const { error } = await supabase.auth.signInWithOtp({
      email,
      options: { emailRedirectTo: `${process.env.NEXT_PUBLIC_SITE_URL ?? ""}/auth/callback?next=/claim` },
    });
    if (error) return { error: error.message };
    return { ok: true, needsVerification: true };
  }

  let groomerId: string | null = null;
  if (listingSlug) {
    // slug is only unique per (city_slug, slug) — two businesses in
    // different metros can share one, so scope by city whenever we have
    // it. Links generated by the site always carry both now; a bare
    // ?listing= from an older link falls back to slug alone and simply
    // won't link if that slug turns out to be ambiguous, rather than
    // risking attaching the claim to the wrong business.
    let query = supabase.from("groomers").select("id").eq("slug", listingSlug);
    if (listingCitySlug) query = query.eq("city_slug", listingCitySlug);
    const { data } = await query.maybeSingle();
    groomerId = data?.id ?? null;
  }

  const { error } = await supabase.from("claims").insert({
    groomer_id: groomerId,
    claimant: user.id,
    business_name: businessName,
    city,
    phone,
    email,
  });

  if (error) return { error: error.message };
  return { ok: true, stored: true };
}
